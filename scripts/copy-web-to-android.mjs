/**
 * Kopíruje webový build z dist/ do Android projektu – náhrada `cap copy android`
 * bez Capacitor CLI.
 *
 * Prečo: `cap copy` / `cap sync` v GitHub Actions zlyháva za 0 s, pretože CLI
 * na čerstvom checkout-e nemá `android/local.properties` a pokúša sa riešiť
 * Android cez `@ionic/utils-process` (process.kill). Tento skript robí presne
 * to, čo CLI robí pri behu a nič viac:
 *   1. skopíruje dist/ → android/app/src/main/assets/public/,
 *   2. zapíše android/app/src/main/assets/capacitor.config.json z capacitor.config.ts,
 *   3. zapíše android/app/src/main/assets/capacitor.plugins.json zo zoznamu pluginov,
 *   4. vygeneruje modul android/capacitor-cordova-android-plugins (je ignorovaný
 *      v gite, ale settings.gradle ho includeuje a capacitor.build.gradle z neho
 *      robí apply from – v čistom checkout-e bez neho Gradle zomrie).
 *
 * Spustenie:  node scripts/copy-web-to-android.mjs
 */
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const DIST = path.join(ROOT, 'dist')
const ASSETS = path.join(ROOT, 'android', 'app', 'src', 'main', 'assets')
const PUBLIC = path.join(ASSETS, 'public')

if (!existsSync(path.join(DIST, 'index.html'))) {
  console.error('dist/index.html neexistuje – najprv spusti `npm run build`.')
  process.exit(1)
}

// 1. webové assety
rmSync(PUBLIC, { recursive: true, force: true })
mkdirSync(PUBLIC, { recursive: true })
cpSync(DIST, PUBLIC, { recursive: true })
console.log('copy dist → android assets/public OK')

// 2. capacitor.config.json – musí byť zhodný s capacitor.config.ts
const capacitorConfig = {
  appId: 'sk.skai.skola',
  appName: 'AI škola',
  webDir: 'dist',
  android: { allowMixedContent: false },
  server: { androidScheme: 'https' },
}
writeFileSync(
  path.join(ASSETS, 'capacitor.config.json'),
  `${JSON.stringify(capacitorConfig, null, '\t')}\n`,
  'utf8',
)
console.log('capacitor.config.json OK')

// 3. capacitor.plugins.json – plugin(y) z package.json dependencies
const pkg = JSON.parse(readFileSync(path.join(ROOT, 'package.json'), 'utf8'))
const PLUGIN_CLASS_PATHS = {
  '@capacitor-community/text-to-speech': 'com.getcapacitor.community.tts.TextToSpeechPlugin',
}
const plugins = Object.keys(pkg.dependencies ?? {})
  .filter((dep) => dep.startsWith('@capacitor/') || dep in PLUGIN_CLASS_PATHS)
  .filter((dep) => dep !== '@capacitor/core' && dep !== '@capacitor/cli')
  .filter((dep) => dep !== '@capacitor/android')
  .map((dep) => ({ pkg: dep, classpath: PLUGIN_CLASS_PATHS[dep] }))
  .filter((p) => p.classpath)

writeFileSync(
  path.join(ASSETS, 'capacitor.plugins.json'),
  `${JSON.stringify(plugins, null, '\t')}\n`,
  'utf8',
)
console.log(`capacitor.plugins.json OK (${plugins.length} pluginov)`)

// 4. modul capacitor-cordova-android-plugins
// android/.gitignore ho ignoruje, ale android/settings.gradle ho `include`uje
// a android/app/capacitor.build.gradle z neho `apply from:` – bez týchto
// súborov Gradle v čistom checkout-e zomrie. Obsah je generovaný Capacitorom,
// uvedený je presne tak, ako ho píše `cap copy`.
const CORDOVA = path.join(ROOT, 'android', 'capacitor-cordova-android-plugins')
mkdirSync(path.join(CORDOVA, 'src', 'main', 'java'), { recursive: true })
mkdirSync(path.join(CORDOVA, 'src', 'main', 'res'), { recursive: true })

writeFileSync(
  path.join(CORDOVA, 'cordova.variables.gradle'),
  `// DO NOT EDIT THIS FILE! IT IS GENERATED EACH TIME "capacitor update" IS RUN
ext {
  cdvMinSdkVersion = project.hasProperty('minSdkVersion') ? rootProject.ext.minSdkVersion : 24
  // Plugin gradle extensions can append to this to have code run at the end.
  cdvPluginPostBuildExtras = []
  cordovaConfig = [:]
}
`,
  'utf8',
)

writeFileSync(
  path.join(CORDOVA, 'build.gradle'),
  `ext {
    androidxAppCompatVersion = project.hasProperty('androidxAppCompatVersion') ? rootProject.ext.androidxAppCompatVersion : '1.7.1'
    cordovaAndroidVersion = project.hasProperty('cordovaAndroidVersion') ? rootProject.ext.cordovaAndroidVersion : '14.0.1'
}

buildscript {
    repositories {
        google()
        mavenCentral()
    }
    dependencies {
        classpath 'com.android.tools.build:gradle:8.13.0'
    }
}

apply plugin: 'com.android.library'

android {
    namespace = "capacitor.cordova.android.plugins"
    compileSdk = project.hasProperty('compileSdkVersion') ? rootProject.ext.compileSdkVersion : 36
    defaultConfig {
        minSdkVersion project.hasProperty('minSdkVersion') ? rootProject.ext.minSdkVersion : 24
        targetSdkVersion project.hasProperty('targetSdkVersion') ? rootProject.ext.targetSdkVersion : 36
        versionCode 1
        versionName "1.0"
    }
    lintOptions {
        abortOnError = false
    }
    compileOptions {
        sourceCompatibility JavaVersion.VERSION_21
        targetCompatibility JavaVersion.VERSION_21
    }
}

repositories {
    google()
    mavenCentral()
    flatDir{
        dirs 'src/main/libs', 'libs'
    }
}

dependencies {
    implementation fileTree(dir: 'src/main/libs', include: ['*.jar'])
    implementation "androidx.appcompat:appcompat:$androidxAppCompatVersion"
    implementation "org.apache.cordova:framework:$cordovaAndroidVersion"
    // SUB-PROJECT DEPENDENCIES START

    // SUB-PROJECT DEPENDENCIES END
}

// PLUGIN GRADLE EXTENSIONS START
apply from: "cordova.variables.gradle"
// PLUGIN GRADLE EXTENSIONS END

for (def func : cdvPluginPostBuildExtras) {
    func()
}
`,
  'utf8',
)

writeFileSync(
  path.join(CORDOVA, 'src', 'main', 'AndroidManifest.xml'),
  `<?xml version='1.0' encoding='utf-8'?>
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
xmlns:amazon="http://schemas.android.com/apk/res/android">
<application  >

</application>

</manifest>
`,
  'utf8',
)

// .gitkeep udržia prázdne res/ a java/ priečinky v repozitárii
for (const dir of ['src/main/java', 'src/main/res']) {
  const keep = path.join(CORDOVA, ...dir.split('/'), '.gitkeep')
  if (!existsSync(keep)) writeFileSync(keep, '', 'utf8')
}
console.log('capacitor-cordova-android-plugins OK')
